// Mechanical responsive-image build only: no crop, recolouring, retouching or
// invented merchandise. The maintained photographs and originals stay intact.
const fs=require('node:fs/promises');const path=require('node:path');
const sharp=require('sharp');
async function main(){
  const root=path.resolve(__dirname,'..');
  const directory=path.join(root,'web/assets/images/customer');
  const output=path.join(directory,'responsive');await fs.mkdir(output,{recursive:true});
  const variants={};
  for(const name of (await fs.readdir(directory)).filter(name=>name.endsWith('.webp')&&!name.endsWith('-480.webp')).sort()){
    const source=path.join(directory,name);const metadata=await sharp(source).metadata();const candidates=[];
    for(const width of [320,640,960]){
      if(width>=metadata.width)continue;
      const target=name.replace('.webp','-'+width+'.webp');
      await sharp(source).resize({width,withoutEnlargement:true}).webp({quality:82,effort:6}).toFile(path.join(output,target));
      candidates.push('/assets/images/customer/responsive/'+target+' '+width+'w');
    }
    const existing480=name.replace('.webp','-480.webp');
    if((await fs.readdir(directory)).includes(existing480))candidates.splice(1,0,'/assets/images/customer/'+existing480+' 480w');
    candidates.push('/assets/images/customer/'+name+' '+metadata.width+'w');
    variants['/assets/images/customer/'+name]=candidates.join(', ');
  }
  const generated='// Code generated by scripts/build-image-variants.cjs; DO NOT EDIT.\npackage components\n\nvar maintainedImageVariants = map[string]string{\n'+Object.entries(variants).map(([key,value])=>'\t'+JSON.stringify(key)+': '+JSON.stringify(value)+',').join('\n')+'\n}\n';
  await fs.writeFile(path.join(root,'web/components/image_variants_generated.go'),generated);
  console.log('Generated proportional responsive variants for '+Object.keys(variants).length+' maintained photographs.');
}
main().catch(error=>{console.error(error);process.exitCode=1;});
